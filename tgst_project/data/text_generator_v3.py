# ── 句式模板 ──────────────────────────────────────────────────
# 不同句式让表面形式更多样

SENTENCE_TEMPLATES = [
    # 2-feature templates
    "{f1}，{f2}",
    "{f1}，{f2}",
    "{f1} {f2}",
    "信号特征：{f1}，{f2}",
    "{f1}，同时{f2}",
]

SENTENCE_TEMPLATES_3 = [
    # 3-feature templates
    "{f1}，{f2}，{f3}",
    "{f1} {f2} {f3}",
    "{f1}，{f2}，且{f3}",
    "特征包括：{f1}，{f2}，{f3}",
    "{f1}，此外{f2}，{f3}",
]

# 连接词变体
CONNECTORS = ["，", "，", "，同时", "，且", "，另外"]


def generate_text_for_label(label: int, rng: random.Random) -> str:
    """
    为指定类别生成一条唯一的文本描述。
    每次调用随机选取 2-3 个特征维度 + 随机句式 + 随机同义表达。
    """
    pool = FEATURE_POOL[label]
    dims = list(pool.keys())
    n_features = rng.choice([2, 3])  # 随机选 2 或 3 个维度

    selected_dims = rng.sample(dims, n_features)
    features = [rng.choice(pool[d]) for d in selected_dims]

    if n_features == 2:
        template = rng.choice(SENTENCE_TEMPLATES)
        return template.format(f1=features[0], f2=features[1])
    else:
        template = rng.choice(SENTENCE_TEMPLATES_3)
        return template.format(f1=features[0], f2=features[1], f3=features[2])


def generate_unique_texts(labels: List[int], seed: int = 42) -> List[str]:
    """
    为标签列表生成唯一文本列表。
    每个样本获得不同的文本描述。
    如果组合空间足够大，几乎不会重复。
    """
    rng = random.Random(seed)
    texts = []
    seen: Set[str] = set()

    for label in labels:
        # 尝试生成唯一文本（最多 100 次重试）
        for _ in range(100):
            text = generate_text_for_label(label, rng)
            if text not in seen:
                seen.add(text)
                texts.append(text)
                break
        else:
            # 极端情况下组合耗尽，加随机后缀
            text = generate_text_for_label(label, rng)
            # 用微小的词序调整保证唯一
            parts = text.split("，")
            rng.shuffle(parts)
            text = "，".join(parts)
            texts.append(text)

    return texts


def compute_combination_space(label: int) -> int:
    """计算某类的组合空间大小"""
    pool = FEATURE_POOL[label]
    dims = list(pool.keys())
    total = 0
    for n in [2, 3]:
        # C(5, n) * 12^n * 5 (句式)
        from math import comb
        c = comb(len(dims), n)
        # 每个选中的维度有约 12 个选项
        avg_choices = 1
        for d in dims:
            avg_choices *= len(pool[d])
        # 近似: C(5,n) * 12^n * 5
        total += c * (12 ** n) * 5
    return total


